// commons.js — コモンイベント（どこからでも呼べる命令のまとまり）
G.defineCommons({
  // Qキー（★）で呼ぶ
  hint: [
    ['popup', '集めたカード：{v:cards} / 3'],
  ],
  // メモを読む（アイテム画面から）
  readMemo: [
    ['text', '', 'メモ：「カードは3枚。部屋・廊下・図書室に1枚ずつ」'],
  ],
  // カードを拾ったとき（各カードのイベントから呼ぶ）
  getCard: [
    ['var', 'cards', '+', 1],
    ['if', { var: ['cards', '>=', 3] }, [
      ['text', '', 'カードが3枚そろった！　ユイに見せに行こう。'],
    ]],
  ],
});
